import { NextRequest, NextResponse } from "next/server";
import fs from "fs";
import path from "path";
import { execFile } from "child_process";
import util from "util";

const execFilePromise = util.promisify(execFile);

function formatAssTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  return `${h}:${m.toString().padStart(2, "0")}:${s.toFixed(2).padStart(5, "0")}`;
}

function hexToAssColor(hex: string, alphaPercent: number = 0): string {
  // hex: "#FFFFFF" -> BGR in ASS format "&HAABBGGRR"
  const clean = hex.replace("#", "");
  const r = clean.substring(0, 2);
  const g = clean.substring(2, 4);
  const b = clean.substring(4, 6);
  // Alpha in ASS: 00 = completely opaque, FF = fully transparent
  const alphaVal = Math.round((alphaPercent / 100) * 255);
  const a = alphaVal.toString(16).padStart(2, "0").toUpperCase();
  return `&H${a}${b.toUpperCase()}${g.toUpperCase()}${r.toUpperCase()}`;
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { cards, styles, videoFile } = body;

    if (!cards || !Array.isArray(cards)) {
      return NextResponse.json({ error: "Missing or invalid cards array" }, { status: 400 });
    }

    const publicDir = path.join(process.cwd(), "public");
    const kakaDir = path.join(publicDir, "videos", "kaka");
    if (!fs.existsSync(kakaDir)) {
      fs.mkdirSync(kakaDir, { recursive: true });
    }

    const fontSize = styles?.fontSize || 84;
    const marginV = styles?.marginV || 375;
    const outline = styles?.strokeEnabled !== false ? (styles?.strokeThickness || 1) * 2 : 0;
    const shadow = styles?.shadowEnabled !== false ? (styles?.shadowDistance || 5) : 0;
    const primaryColor = hexToAssColor(styles?.fontColor || "#FFFFFF", 0);
    const outlineColor = hexToAssColor(styles?.strokeColor || "#000000", 0);
    // In CapCut: opacity 40% -> in ASS alpha is 60% transparent (0x99) or 40% transparent
    const shadowOpacity = styles?.shadowOpacity !== undefined ? (100 - styles.shadowOpacity) : 60;
    const backColor = hexToAssColor(styles?.shadowColor || "#000000", shadowOpacity);
    const spacing = styles?.letterSpacing !== undefined ? styles.letterSpacing : -1;

    // Build ASS Header
    let assContent = `[Script Info]
; Script generated by Motion Review Studio Caption Dashboard
Title: Dr Kaka Captions Custom
ScriptType: v4.00+
WrapStyle: 0
PlayResX: 1080
PlayResY: 1920
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Poppins,${fontSize},${primaryColor},&H000000FF,${outlineColor},${backColor},-1,0,0,0,100,100,${spacing},0,1,${outline},${shadow},2,40,40,${marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

    for (const card of cards) {
      const start = formatAssTime(card.start);
      const end = formatAssTime(card.end);

      const wordTokens: string[] = [];
      if (card.words && Array.isArray(card.words)) {
        for (const w of card.words) {
          const text = w.text || "";
          if (w.isEmphasis) {
            wordTokens.push(`{\\fnPlayfair Display\\i1\\b0}${text}{\\fnPoppins\\i0\\b1}`);
          } else {
            wordTokens.push(text);
          }
        }
      } else {
        wordTokens.push(card.text || "");
      }

      const dialogueText = wordTokens.join(" ");
      assContent += `Dialogue: 0,${start},${end},Default,,0,0,0,,{\\fnPoppins\\b1}${dialogueText}\n`;
    }

    const assFilePath = path.join(kakaDir, "is_glp_safe_custom.ass");
    fs.writeFileSync(assFilePath, assContent, "utf-8");

    // Also write updated SRT
    let srtContent = "";
    cards.forEach((card, idx) => {
      const formatSrtTime = (sec: number) => {
        const h = Math.floor(sec / 3600).toString().padStart(2, "0");
        const m = Math.floor((sec % 3600) / 60).toString().padStart(2, "0");
        const s = Math.floor(sec % 60).toString().padStart(2, "0");
        const ms = Math.floor((sec % 1) * 1000).toString().padStart(3, "0");
        return `${h}:${m}:${s},${ms}`;
      };
      srtContent += `${idx + 1}\n${formatSrtTime(card.start)} --> ${formatSrtTime(card.end)}\n${card.text}\n\n`;
    });
    fs.writeFileSync(path.join(kakaDir, "is_glp_safe_custom.srt"), srtContent, "utf-8");

    // Source video resolution
    const sourceVideo = path.join(kakaDir, "is_glp_safe_raw.mp4");
    const outputVideo = path.join(kakaDir, "is_glp_safe_rendered.mp4");

    if (!fs.existsSync(sourceVideo)) {
      return NextResponse.json({
        success: true,
        message: "ASS and SRT saved successfully (raw video not found for re-encoding)",
        assUrl: "/videos/kaka/is_glp_safe_custom.ass",
        srtUrl: "/videos/kaka/is_glp_safe_custom.srt",
      });
    }

    // Font directories
    const fontDir = "C:/Users/Windows/AppData/Local/CapCut/User Data/Cache/effect/13566112/b1cf90c4dfe0b371aaa411aaae3a33d0";
    const assClean = assFilePath.replace(/\\/g, "/").replace(":", "\\:");
    const fontClean = fontDir.replace(/\\/g, "/").replace(":", "\\:");
    const assFilter = `ass='${assClean}':fontsdir='${fontClean}'`;

    console.log("Starting FFmpeg re-render with updated captions...");
    await execFilePromise("ffmpeg", [
      "-i", sourceVideo,
      "-vf", assFilter,
      "-c:v", "libx264",
      "-crf", "18",
      "-preset", "veryfast",
      "-c:a", "copy",
      outputVideo,
      "-y"
    ]);

    return NextResponse.json({
      success: true,
      message: "Render completed successfully!",
      videoUrl: `/videos/kaka/is_glp_safe_rendered.mp4?t=${Date.now()}`,
      assUrl: `/videos/kaka/is_glp_safe_custom.ass?t=${Date.now()}`,
      srtUrl: `/videos/kaka/is_glp_safe_custom.srt?t=${Date.now()}`,
    });
  } catch (error: any) {
    console.error("Caption render API error:", error);
    return NextResponse.json({ error: error.message || "Failed to render captions" }, { status: 500 });
  }
}
